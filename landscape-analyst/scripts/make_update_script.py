#!/usr/bin/env python3
"""Generate {theme}/collect_update.sh from the queries recorded in the manifest.

The collection tool records every executed query in manifest `runs[]`
(per-source `query_string`, date window, result count). This script turns that
record into a re-runnable batch script stored WITH the theme's outputs, so the
same searches can be run periodically: every invocation uses `--update`, which
fetches only new canonical IDs and never touches agent judgment fields.

The generated script is a starting point — hand-edit it to add new query nets;
new queries run against the same manifest and merge safely.

Only reads the manifest; writes only {theme}/collect_update.sh (contract-safe).

Usage:
    python make_update_script.py {theme}/manifest.json [--mailto you@example.com]
"""
from __future__ import annotations

import argparse
import json
import stat
from pathlib import Path

HEADER = """#!/usr/bin/env bash
#
# collect_update.sh — periodic re-collection for theme {theme!r}
# GENERATED by landscape-analyst/scripts/make_update_script.py from the
# queries recorded in manifest.json runs[] (generated {generated}; edit freely —
# regenerating only adds queries executed since).
#
# Every run uses --update: only new canonical IDs are fetched and merged;
# prior curation (status, scores, dimensions, clusters) is preserved.
# After collecting, re-run Phase B (landscape-analyst skill, Update mode)
# to score the new records and refresh both reports.
#
# USAGE
#   ./collect_update.sh
#   MAX_RESULTS=50 SOURCES=arxiv ./collect_update.sh   # override inline

set -uo pipefail   # NOT -e: one failed run should not kill the batch.

THEME={theme_sh}
THEME_DIR="$(cd "$(dirname "$0")" && pwd)"
BASE_DIR="${{BASE_DIR:-$(dirname "$THEME_DIR")}}"
MAX_RESULTS="${{MAX_RESULTS:-100}}"
MAILTO="${{MAILTO:-{mailto}}}"

run() {{
  local label="$1" sources="$2" since="$3" query="$4"
  echo ""
  echo ">>> [$label] sources=$sources since=${{since:-none}}"
  echo "    query: $query"
  python -m landscape collect \\
    --theme "$THEME" \\
    --query "$query" \\
    ${{since:+--since "$since"}} \\
    --sources "${{SOURCES:-$sources}}" \\
    --max-results "$MAX_RESULTS" \\
    --base-dir "$BASE_DIR" \\
    --mailto "$MAILTO" \\
    --update \\
    || echo "!! [$label] run returned non-zero — continuing."
}}
"""

FOOTER = """
echo ""
echo "Done. Re-run Phase B (landscape-analyst skill, Update mode) to curate new records."
"""


def sh_quote(s: str) -> str:
    return "'" + s.replace("'", "'\\''") + "'"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("manifest")
    ap.add_argument("--mailto", default="you@example.com",
                    help="polite-pool contact passed to the tool")
    args = ap.parse_args(argv)

    mpath = Path(args.manifest)
    manifest = json.loads(mpath.read_text())
    theme = manifest.get("theme") or mpath.parent.name

    # ordered unique queries; union sources, keep the widest date window seen
    queries: dict[str, dict] = {}
    for run in manifest.get("runs", []):
        for s in run.get("sources", []):
            q = s.get("query_string")
            if not q:
                continue
            entry = queries.setdefault(q, {"sources": [], "since": None})
            if s["source"] not in entry["sources"]:
                entry["sources"].append(s["source"])
            since = (s.get("date_window") or {}).get("since")
            if since and (entry["since"] is None or since < entry["since"]):
                entry["since"] = since
    if not queries:
        print(f"no queries recorded in {mpath} runs[] — nothing to generate")
        return 1

    generated = manifest.get("last_updated") or manifest.get("created") or "unknown"
    lines = [HEADER.format(theme=theme, theme_sh=sh_quote(theme),
                           mailto=args.mailto, generated=generated)]
    for i, (q, entry) in enumerate(queries.items(), 1):
        lines.append(f'run "q{i}" {sh_quote(",".join(entry["sources"]))} '
                     f'{sh_quote(entry["since"] or "")} \\\n  {sh_quote(q)}\n')
    lines.append(FOOTER)

    out = mpath.parent / "collect_update.sh"
    out.write_text("".join(lines))
    out.chmod(out.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    print(f"wrote {out} ({len(queries)} quer{'y' if len(queries)==1 else 'ies'})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
